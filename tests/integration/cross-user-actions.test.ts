import {expect,it,vi} from 'vitest';
import bcrypt from 'bcryptjs';
import {prisma} from '../fixtures/database';
import type {Actor} from '@/features/identity/model/session';
const context=vi.hoisted(()=>({actor:null as Actor|null}));
vi.mock('@/features/identity/server/actor',()=>({getActor:async(roles?:string[])=>context.actor&&(!roles||roles.includes(context.actor.role))?context.actor:null}));
import {updateProfileAction} from '@/features/identity/server/profile-actions';
import {changePasswordAction} from '@/features/identity/server/account-actions';
import {updateUserRoleAction,deleteMemberAction} from '@/features/identity/server/member-actions';
import {saveShowcaseDraftAction,submitShowcaseForReviewAction} from '@/features/submissions/server/actions';
import {removeAvatarAction} from '@/features/assets/server/avatar-actions';
it('uses the authenticated actor despite forged target IDs and rejects cross-user privileged mutations',async()=>{
 const passwordHash=await bcrypt.hash('Original-password-2026!',4);
 const a=await prisma.user.create({data:{email:'actor-a@test.invalid',fullName:'Actor A',passwordHash,role:'CORE_MEMBER',status:'ACTIVE'}});
 const b=await prisma.user.create({data:{email:'actor-b@test.invalid',fullName:'Actor B',passwordHash,role:'MEMBER',status:'ACTIVE'}});
 context.actor={id:a.id,fullName:a.fullName,role:a.role,status:'ACTIVE',mustChangePassword:false};
 const before=await prisma.user.findUniqueOrThrow({where:{id:b.id}});
 const profile={fullName:'Actor A updated',bio:'Own profile',links:[],userId:b.id,id:b.id};
 expect(await updateProfileAction(profile)).toMatchObject({success:true});
 expect((await prisma.user.findUniqueOrThrow({where:{id:a.id}})).fullName).toBe('Actor A updated');
 expect(await updateUserRoleAction(b.id,'ADMIN')).toMatchObject({success:false});
 expect(await deleteMemberAction(b.id)).toMatchObject({success:false});
 const remove=removeAvatarAction as unknown as (input:unknown)=>ReturnType<typeof removeAvatarAction>;
 expect(await remove({userId:b.id})).toMatchObject({success:true});
 expect(await changePasswordAction({currentPassword:'Original-password-2026!',newPassword:'New-password-2026!',userId:b.id} as Parameters<typeof changePasswordAction>[0])).toMatchObject({success:true});
 expect(await prisma.user.findUniqueOrThrow({where:{id:b.id}})).toEqual(before);
 const item=await prisma.showcaseItem.create({data:{creatorId:b.id,title:'B private draft',slug:'b-private-draft',summary:'Private'}});
 expect(await saveShowcaseDraftAction({itemId:item.id,expectedReviewVersion:0,draft:{title:'Forged update'}})).toMatchObject({success:false,code:'FORBIDDEN'});
 expect(await submitShowcaseForReviewAction({itemId:item.id,expectedReviewVersion:0})).toMatchObject({success:false,code:'FORBIDDEN'});
 expect((await prisma.showcaseItem.findUniqueOrThrow({where:{id:item.id}})).title).toBe('B private draft');
 context.actor=null;
 expect(await updateProfileAction({fullName:'Guest',bio:'',links:[]})).toMatchObject({success:false,code:'UNAUTHORIZED'});
});
